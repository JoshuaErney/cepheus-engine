// Cascade skills (Gun Combat, Melee Combat, Gunnery, Vehicle, Aircraft, Watercraft, Animals,
// Sciences) are printed in the SRD career tables under their generic cascade name, with no
// specific specialty called out — the specialty is chosen by the player when the skill is
// taken (per "Cascade Skills", p.29). They are transcribed here as the canonical cascade
// skill item name from skills.mjs, e.g. "Gun Combat (Cascade Skill)".
//
