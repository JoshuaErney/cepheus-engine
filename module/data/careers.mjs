// "Table: Available Skills" (p.48) and are almost certainly leftover/erroneous text from an
// earlier edition of the career tables:
//   - Bureaucrat, Specialist Skills, row 3: printed as "Perception" -> mapped to "Recon"
//     (closest official skill; SRD has no "Perception" skill).
//   - Belter, Service Skills row 5 and Specialist Skills row 4: printed as "Prospecting"
//     -> mapped to "Physical Sciences" (covers geology/mineral prospecting; SRD has no
//     "Prospecting" skill).
// Both were double-checked against the source PDF directly (not just the text extraction)
// and confirmed to be printed that way. Flagged here for manual double-check against a
// different SRD printing if one is available.
//
// Ranks/commissions: per the SRD ("Commission and Advancement", p.29), the Athlete,
// Barbarian, Belter, Drifter, Entertainer, Hunter, and Scout careers have no commission or
// advancement rolls, and thus no rank hierarchy — commission/advancement are null for these,
// and rankTitles is a flat repeated placeholder since the source table has no titles for them.
//
// Cash/benefits: the SRD's tables print 7 rows (rows 1-6 for a plain 1D6 roll, plus a row 7
// that only comes into play from the +1 DM some characters get on mustering-out rolls).
// module/apps/chargen.mjs rolls a plain 1D6 (idx = roll - 1, range 0-5) with no DM, so only
// the 6-element form matters here; row 7 has been dropped.

